#!/usr/bin/env python3
"""Put voice lines from the Emberstage studio into the game.

    python3 tools/import_voices.py path/to/trio-voices-approved-YYYY-MM-DD.zip

What it does:
  1. Reads manifest.json from the studio's export zip (WAV files with effects already applied).
  2. Converts each WAV to OGG Vorbis (small, good quality, Godot's preferred compressed format) into
     godot/assets/voices/<character>/<name>.ogg
  3. Updates godot/scripts/voice_index.gd (line text → file), replacing an older file for the same line.
  4. Lists any lines that are no longer in the game's scripts (reworded since the voice was made).
Then run `godot --headless --path godot --import`, commit, and push: the Windows build picks it up.
Needs ffmpeg.
"""
import json, os, re, subprocess, sys, zipfile, tempfile, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
VOICES = ROOT / "godot" / "assets" / "voices"
INDEX = ROOT / "godot" / "scripts" / "voice_index.gd"
SCRIPTS = ROOT / "godot" / "scripts"

def key(line):
    return re.sub(r"[^a-z0-9]", "", line.lower())

def load_index():
    entries = {}
    if INDEX.exists():
        for m in re.finditer(r'^\t"([a-z0-9]+)": "([^"]+)",\s*#\s?(.*)$', INDEX.read_text(), re.M):
            entries[m.group(1)] = (m.group(2), m.group(3))
    return entries

def write_index(entries):
    lines = [
        "# Generated by tools/import_voices.py from the Emberstage voice studio. Don't edit by hand: re-import instead.",
        "# key (line text, lowercase letters+digits only) → file under res://assets/voices/   # the line as written",
        "class_name VoiceIndex",
        "",
        "const LINES := {",
    ]
    for k, (path, text) in sorted(entries.items(), key=lambda kv: (kv[1][0].split("/")[0], kv[1][0])):
        lines.append(f'\t"{k}": "{path}",  # {text}')
    lines += ["}", ""]
    INDEX.write_text("\n".join(lines))

def game_keys():
    keys = set()
    for p in SCRIPTS.rglob("*.gd"):
        for m in re.finditer(r'"((?:[^"\\]|\\.)*)"', p.read_text()):
            keys.add(key(m.group(1).replace('\\"', '"')))
    return keys

def main():
    if len(sys.argv) < 2:
        print(__doc__); sys.exit(1)
    z = zipfile.ZipFile(sys.argv[1])
    manifest = json.loads(z.read("manifest.json"))
    entries = load_index()
    known = game_keys()
    added, replaced, stale = 0, 0, []
    with tempfile.TemporaryDirectory() as tmp:
        for e in manifest:
            k = e.get("key") or key(e["line"])
            who = re.sub(r"[^a-z0-9_]", "", e["who"].lower()) or "misc"
            base = pathlib.Path(e["file"]).stem
            rel = f"{who}/{base}.ogg"
            src = pathlib.Path(tmp) / "in.wav"
            src.write_bytes(z.read(e["file"]))
            out = VOICES / rel
            out.parent.mkdir(parents=True, exist_ok=True)
            subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(src), "-ac", "1", "-c:a", "libvorbis", "-q:a", "5", str(out)], check=True)
            old = entries.get(k)
            if old and old[0] != rel:
                for f in (VOICES / old[0], VOICES / (old[0] + ".import")):
                    if f.exists(): f.unlink()
                replaced += 1
            elif not old:
                added += 1
            entries[k] = (rel, e["line"].replace("\n", " "))
            if k not in known:
                stale.append(e["line"])
    write_index(entries)
    print(f"{len(manifest)} voice lines imported ({added} new, {replaced} replaced). Index now has {len(entries)} lines.")
    if stale:
        print(f"\n{len(stale)} line(s) aren't in the game's scripts anymore (reworded?), so they won't play:")
        for s in stale[:20]: print("  -", s)
    print("\nNext: godot --headless --path godot --import, then commit + push (the Windows build updates itself).")

main()
